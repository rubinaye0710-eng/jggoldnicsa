create table if not exists public.proveedores (
 proveedor_id bigint generated by default as identity primary key,
 nombre varchar(100) not null, direccion varchar(255), telefono varchar(15)
);
create table if not exists public.clientes (
 cliente_id bigint generated by default as identity primary key,
 nombre varchar(100) not null, cedula varchar(20), foto_cedula text not null,
 direccion varchar(255), telefono varchar(15), created_at timestamptz not null default now()
);
create table if not exists public.factura_contadores (
 proveedor_id bigint primary key references public.proveedores(proveedor_id),
 contador_actual bigint not null default 0
);
create table if not exists public.facturas (
 factura_id bigint generated by default as identity primary key,
 proveedor_id bigint not null references public.proveedores(proveedor_id),
 cliente_id bigint not null references public.clientes(cliente_id),
 numero_factura bigint unique, fecha date not null default current_date,
 ruc text not null, uag text not null, created_at timestamptz not null default now()
);
create table if not exists public.detalles_factura (
 detalle_id bigint generated by default as identity primary key,
 factura_id bigint not null references public.facturas(factura_id) on delete cascade,
 descripcion varchar(255), cantidad integer not null,
 fecha_entrega date not null, cierre varchar(50), gramos numeric(10,2) not null,
 precio_por_gramo numeric(10,2) not null, kilataje varchar(50),
 onzas numeric(10,2), punto numeric(10,2), precio_total numeric(12,2) not null
);

-- Crear factura en una sola transacción y reservar número sin colisiones.
create or replace function public.crear_factura(p_payload jsonb)
returns bigint language plpgsql security definer set search_path=public
as $$
declare
 v_cliente_id bigint; v_factura_id bigint; v_numero bigint; v_proveedor bigint;
 v_detalle jsonb;
begin
 if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
 v_proveedor := (p_payload->>'proveedor_id')::bigint;
 if not exists(select 1 from proveedores where proveedor_id=v_proveedor) then
   raise exception 'Proveedor no válido.';
 end if;
 insert into clientes(nombre,telefono,cedula,direccion,foto_cedula)
 values(p_payload#>>'{cliente,nombre}',p_payload#>>'{cliente,telefono}',
        p_payload#>>'{cliente,cedula}',p_payload#>>'{cliente,direccion}',
        p_payload#>>'{cliente,foto_cedula}')
 returning cliente_id into v_cliente_id;
 update factura_contadores set contador_actual=contador_actual+1
 where proveedor_id=v_proveedor returning contador_actual into v_numero;
 if v_numero is null then raise exception 'No existe contador para este proveedor.'; end if;
 insert into facturas(proveedor_id,cliente_id,numero_factura,ruc,uag)
 values(v_proveedor,v_cliente_id,v_numero,p_payload->>'ruc',p_payload->>'uag')
 returning factura_id into v_factura_id;
 for v_detalle in select * from jsonb_array_elements(p_payload->'detalles') loop
  insert into detalles_factura(factura_id,descripcion,cantidad,fecha_entrega,cierre,
   gramos,precio_por_gramo,kilataje,onzas,punto,precio_total)
  values(v_factura_id,v_detalle->>'descripcion',(v_detalle->>'cantidad')::integer,
   (v_detalle->>'fecha_entrega')::date,v_detalle->>'cierre',
   (v_detalle->>'gramos')::numeric,(v_detalle->>'precio_por_gramo')::numeric,
   nullif(v_detalle->>'kilataje',''),nullif(v_detalle->>'onzas','')::numeric,
   nullif(v_detalle->>'punto','')::numeric,
   (v_detalle->>'precio_total')::numeric);
 end loop;
 return v_factura_id;
end; $$;
revoke all on function public.crear_factura(jsonb) from public;
grant execute on function public.crear_factura(jsonb) to authenticated;

-- Seguridad: todos los registros requieren sesión autenticada.
alter table public.proveedores enable row level security;
alter table public.clientes enable row level security;
alter table public.factura_contadores enable row level security;
alter table public.facturas enable row level security;
alter table public.detalles_factura enable row level security;
create policy "auth read providers" on public.proveedores for select to authenticated using(true);
create policy "auth read clients" on public.clientes for select to authenticated using(true);
create policy "auth read counters" on public.factura_contadores for select to authenticated using(true);
create policy "auth read invoices" on public.facturas for select to authenticated using(true);
create policy "auth delete invoices" on public.facturas for delete to authenticated using(true);
create policy "auth read invoice details" on public.detalles_factura for select to authenticated using(true);

-- Permisos SQL para las operaciones que realiza el cliente web.
grant select on public.proveedores, public.clientes, public.factura_contadores,
 public.facturas, public.detalles_factura to authenticated;
grant delete on public.facturas to authenticated;

